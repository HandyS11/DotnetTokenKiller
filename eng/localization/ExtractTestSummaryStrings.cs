// Prints src/DotnetTokenKiller.Application/Filters/LocalizedTestSummaryStrings.cs: the summary-line strings of
// `dotnet test`, in every language a .NET SDK ships, read from the SDK's own satellite resource assemblies.
//
//   dotnet run eng/localization/ExtractTestSummaryStrings.cs -- /usr/share/dotnet/sdk/10.0.403 \
//       > src/DotnetTokenKiller.Application/Filters/LocalizedTestSummaryStrings.cs
//
// It reads VSTest's console-logger strings (vstest.console.dll) and the strings `dotnet test` prints under
// Microsoft.Testing.Platform (dotnet.dll), from the neutral assembly in <sdk dir> and from the satellite
// <sdk dir>/<culture>/<name>.resources.dll of each culture. A translation identical to the neutral (English)
// string is left out, so no entry can match English output, which dtk parses normally.
#:property PublishAot=false
#:property GenerateDocumentationFile=false

using System.Collections;
using System.Globalization;
using System.Reflection;
using System.Resources;
using System.Text;

if (args.Length != 1 || !Directory.Exists(args[0]))
{
    await Console.Error.WriteLineAsync("usage: dotnet run eng/localization/ExtractTestSummaryStrings.cs -- <sdk dir>")
        .ConfigureAwait(false);
    return 2;
}

var sdkDir = Path.GetFullPath(args[0]);
var sdkVersion = SdkVersion(sdkDir);

// The summary lines dtk keys on: VSTest's minimal `Passed!/Failed!/Skipped! - Failed: …` line and its
// normal-logger `Test Run …` verdict lines; MTP's `Test run summary:` header.
(string Assembly, string BaseName, string[] Keys)[] sources =
[
    ("vstest.console", "Microsoft.VisualStudio.TestPlatform.CommandLine.Resources.Resources",
        ["TestRunSummary", "TestRunSuccessful", "TestRunFailed", "TestRunAborted", "TestRunAbortedWithError",
            "TestRunCanceled"]),
    ("dotnet", "Microsoft.DotNet.Cli.Commands.CliCommandStrings", ["TestRunSummary"]),
];

var cultures = Directory.GetDirectories(sdkDir)
    .Select(Path.GetFileName)
    .OfType<string>()
    .Where(name => sources.Any(source => File.Exists(SatellitePath(sdkDir, name, source.Assembly))))
    .Order(StringComparer.Ordinal)
    .ToList();
var entries = sources
    .SelectMany(source => ReadEntries(sdkDir, cultures, source.Assembly, source.BaseName, source.Keys))
    .OrderBy(entry => entry.Culture, StringComparer.Ordinal)
    .DistinctBy(entry => (entry.Culture, entry.Format))
    .ToList();

var output = new StringBuilder()
    .Append("// <auto-generated>\n")
    .Append(CultureInfo.InvariantCulture,
        $"//     Generated by eng/localization/ExtractTestSummaryStrings.cs from .NET SDK {sdkVersion}: the\n")
    .Append("//     summary-line strings of vstest.console.dll and dotnet.dll, read from their satellite resource\n")
    .Append("//     assemblies under <sdk dir>/<culture>/. Do not edit by hand; regenerate with\n")
    .Append("//     `dotnet run eng/localization/ExtractTestSummaryStrings.cs -- <sdk dir>`.\n")
    .Append("// </auto-generated>\n")
    .Append('\n')
    .Append("namespace DotnetTokenKiller.Application.Filters;\n")
    .Append('\n')
    .Append("/// <summary>\n")
    .Append("/// The translated summary lines of <c>dotnet test</c>, per culture the .NET SDK ships:\n")
    .Append("/// VSTest's <c>TestRunSummary</c> (<c>{0} - Failed: {1}, Passed: {2}, …</c>) and\n")
    .Append("/// <c>Test Run …</c> verdicts, and the <c>Test run summary:</c> header <c>dotnet test</c>\n")
    .Append("/// prints under Microsoft.Testing.Platform. Each format is kept raw, placeholders included;\n")
    .Append("/// none equals its English original.\n")
    .Append("/// </summary>\n")
    .Append("internal static class LocalizedTestSummaryStrings\n")
    .Append("{\n")
    .Append("    /// <summary>The .NET SDK whose satellite assemblies the table was read from.</summary>\n")
    .Append(CultureInfo.InvariantCulture, $"    internal const string SdkVersion = \"{sdkVersion}\";\n")
    .Append('\n')
    .Append("    /// <summary>Each culture's summary-line formats, by culture name, as the SDK words them.</summary>\n")
    .Append("    internal static IReadOnlyList<(string Culture, string Format)> Entries { get; } =\n")
    .Append("    [\n");

foreach (var (culture, source, format) in entries)
{
    output.Append(CultureInfo.InvariantCulture,
        $"        (\"{culture}\", \"{Escape(format)}\"), // {source}\n");
}

output.Append("    ];\n").Append("}\n");
await Console.Out.WriteAsync(output.ToString()).ConfigureAwait(false);

// Several cultures sharing a format is harmless (the first in culture order names the match), but worth knowing.
foreach (var shared in entries.GroupBy(e => e.Format, StringComparer.Ordinal).Where(g => g.Count() > 1))
{
    await Console.Error.WriteLineAsync(
            $"note: {string.Join(", ", shared.Select(e => e.Culture))} share \"{shared.Key}\"")
        .ConfigureAwait(false);
}

return 0;

static string SdkVersion(string sdkDir)
{
    // An SDK's .version file holds the commit, then the version, then the RID.
    var versionFile = Path.Combine(sdkDir, ".version");
    var lines = File.Exists(versionFile) ? File.ReadAllLines(versionFile) : [];
    return lines.Length > 1 ? lines[1].Trim() : Path.GetFileName(sdkDir);
}

static string SatellitePath(string sdkDir, string culture, string assembly) =>
    Path.Combine(sdkDir, culture, assembly + ".resources.dll");

static IEnumerable<(string Culture, string Source, string Format)> ReadEntries(
    string sdkDir, List<string> cultures, string assembly, string baseName, string[] keys)
{
    var neutral = ReadStrings(Path.Combine(sdkDir, assembly + ".dll"), baseName + ".resources");
    if (keys.FirstOrDefault(key => !neutral.ContainsKey(key)) is { } missing)
    {
        throw new InvalidOperationException($"{assembly}.dll has no {missing} string");
    }

    foreach (var culture in cultures)
    {
        var satellite = ReadStrings(SatellitePath(sdkDir, culture, assembly), $"{baseName}.{culture}.resources");

        // Left out when missing, untranslated, or nothing but placeholders: such a format would match English
        // output, or any line at all.
        foreach (var key in keys)
        {
            if (satellite.TryGetValue(key, out var format)
                && !string.Equals(format, neutral[key], StringComparison.Ordinal)
                && HasLiteralText(format))
            {
                yield return (culture, $"{assembly} {key}", format);
            }
        }
    }
}

static Dictionary<string, string> ReadStrings(string assemblyPath, string resourceName)
{
    var assembly = Assembly.LoadFrom(assemblyPath);
    using var stream = assembly.GetManifestResourceStream(resourceName)
        ?? throw new InvalidOperationException($"{assemblyPath} has no {resourceName} resource");
    using var reader = new ResourceReader(stream);
    var strings = new Dictionary<string, string>(StringComparer.Ordinal);
    foreach (DictionaryEntry entry in reader)
    {
        if (entry.Value is string value)
        {
            strings[(string)entry.Key] = value;
        }
    }

    return strings;
}

static bool HasLiteralText(string format)
{
    var depth = 0;
    foreach (var c in format)
    {
        if (c == '{')
        {
            depth++;
        }
        else if (c == '}')
        {
            depth = Math.Max(0, depth - 1);
        }
        else if (depth == 0 && !char.IsWhiteSpace(c) && !char.IsPunctuation(c))
        {
            return true;
        }
    }

    return false;
}

static string Escape(string value)
{
    var sb = new StringBuilder(value.Length);
    foreach (var c in value)
    {
        switch (c)
        {
            case '"':
                sb.Append("\\\"");
                break;
            case '\\':
                sb.Append(@"\\");
                break;
            case '\n':
                sb.Append("\\n");
                break;
            case '\r':
                sb.Append("\\r");
                break;
            case '\t':
                sb.Append("\\t");
                break;
            default:
                // Escaped so the table shows them: a non-breaking or narrow space, a direction mark, a control.
                var category = char.GetUnicodeCategory(c);
                var invisible = (c != ' ' && char.IsWhiteSpace(c))
                    || category is UnicodeCategory.Control or UnicodeCategory.Format
                        or UnicodeCategory.LineSeparator or UnicodeCategory.ParagraphSeparator;
                if (invisible)
                {
                    sb.Append(CultureInfo.InvariantCulture, $"\\u{(int)c:X4}");
                }
                else
                {
                    sb.Append(c);
                }

                break;
        }
    }

    return sb.ToString();
}
